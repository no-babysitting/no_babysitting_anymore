// usage: node tools/fetch-fonts.cjs   → site/public/fonts/*.woff2 + site/public/fonts/fonts.css
// Self-hosts the web fonts the site used to load from Google Fonts (issue #28): the visitor's IP is no longer sent to Google.
// It asks Google Fonts for the same families, weights and axes as before, keeps the subsets a Vietnamese page can use
// (latin, latin-ext, vietnamese), downloads each woff2 next to the CSS and writes fonts.css with relative urls
// (so it works under any base path). Run it again to update the files; commit the result.
const { execFileSync } = require('child_process');
const fs = require('fs'), path = require('path');
const OUT = path.join(__dirname, '..', 'site', 'public', 'fonts');
const FAMILIES = 'family=Archivo:wdth,wght@62..125,400..900&family=Be+Vietnam+Pro:ital,wght@0,400;0,500;0,600;1,400&family=JetBrains+Mono:ital,wght@0,400;0,500;0,600;1,400;1,600&family=Newsreader:ital,opsz,wght@0,6..72,400;0,6..72,500;1,6..72,400';
const KEEP = new Set(['latin', 'latin-ext', 'vietnamese']);
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36'; // asks for woff2
const curl = (args) => execFileSync('curl', ['-sS', '-m', '60', '-A', UA, '--fail', ...args], { maxBuffer: 1 << 26 });
const css = curl([`https://fonts.googleapis.com/css2?${FAMILIES}&display=swap`]).toString('utf8');
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
if (!blocks.length) throw new Error('no @font-face blocks in the response');
fs.mkdirSync(OUT, { recursive: true });
const get = (b, k) => (b.match(new RegExp(k + ':\\s*([^;]+);')) || [])[1]?.trim();
const out = ['/* Generated by tools/fetch-fonts.cjs (issue #28). SIL Open Font License 1.1; see THIRD_PARTY_NOTICES.md. */'];
const seen = new Map(); let kept = 0, bytes = 0;
for (const [, subset, body] of blocks) {
  if (!KEEP.has(subset)) continue;
  const family = get(body, 'font-family').replace(/['"]/g, ''), style = get(body, 'font-style'), weight = get(body, 'font-weight');
  const stretch = get(body, 'font-stretch'), range = get(body, 'unicode-range'), src = body.match(/url\(([^)]+)\)/)[1];
  const slug = family.toLowerCase().replace(/\s+/g, '-') + '-' + (style === 'italic' ? 'i' : 'n') + '-' + weight.replace(/\s+/g, '-') + '-' + subset + '.woff2';
  const key = src; // the same file can serve several weights of a variable font
  let file = seen.get(key);
  if (!file) { file = slug; fs.writeFileSync(path.join(OUT, file), curl([src])); seen.set(key, file); bytes += fs.statSync(path.join(OUT, file)).size; }
  out.push(`@font-face { font-family: '${family}'; font-style: ${style}; font-weight: ${weight};${stretch ? ' font-stretch: ' + stretch + ';' : ''} font-display: swap; src: url(./${file}) format('woff2'); unicode-range: ${range}; }`);
  kept++;
}
fs.writeFileSync(path.join(OUT, 'fonts.css'), out.join('\n') + '\n');
console.log(`${kept} @font-face rules, ${seen.size} files, ${(bytes / 1024).toFixed(0)} KB`);
