#!/usr/bin/env python3
"""Port design-system previews into Astro components (src/components/ds/<Name>.astro).
Markup is kept as-is, CSS is scoped under .ds-<Name>, the script runs once GSAP is on window
('nb:gsap'). Props: optional literal -> {expr} replacements per component (PROPS below).
The previews stay the source of truth: re-run this after changing one."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
DS = os.path.join(HERE, '..', '..', 'design-system', 'components')
OUT = os.path.join(HERE, '..', 'src', 'components', 'ds')
PLUGINS = ['ScrambleTextPlugin', 'SplitText', 'Flip', 'DrawSVGPlugin', 'MorphSVGPlugin', 'MotionPathPlugin', 'CustomEase']

# literal markup -> Astro expression, and frontmatter props, per component
PROPS = {
  'ChapterOpener': {
    'front': "const { id, no, en, vi, part, ghost, total = 12, beats = 8, mins = '' } = Astro.props;",
    'body': [
      ('<span class="nb-ghost gh" aria-hidden="true">Budget</span>', '<span class="nb-ghost gh" aria-hidden="true">{ghost}</span>'),
      ('<span class="nb-sq"></span>Phần I · LOW</span>', '<span class="nb-sq"></span>{part}</span>'),
      ('c02 &nbsp;·&nbsp; <b id="clk"', '{id} &nbsp;·&nbsp; <b id="clk"'),
      ('<b>02</b> / 10 &nbsp;·&nbsp; 8 beat · 10′', '<b>{no}</b> / {total} &nbsp;·&nbsp; {beats} beat{mins && ` · ${mins}′`}'),
      ('id="idx" aria-hidden="true">02</p>', 'id="idx" aria-hidden="true">{no}</p>'),
      ('<span class="nb-sq"></span>Chương 02</p>', '<span class="nb-sq"></span>{no === "00" ? "Mở đầu" : `Chương ${no}`}</p>'),
      ('<h2 class="nb-wide" id="t">The Briefing Budget</h2>', '<h1 class="nb-wide" id="t">{en}</h1>'),
      ('<p class="sub">Ngân sách ngữ cảnh: vì sao Claude "ngốc dần" về cuối buổi, và làm gì sau mỗi lượt.</p>', '<p class="sub">{vi}</p>'),
    ],
    'script': [("NB.say(document.getElementById('m1'), 'Phần I · LOW');", "var m1 = document.getElementById('m1'); NB.say(m1, m1.textContent);")],
  },
}

def scope(css, p):
    out, i = [], 0
    while i < len(css):
        j = css.find('{', i)
        if j < 0: break
        sel = css[i:j].strip()
        depth, k = 1, j + 1
        while depth:
            depth += {'{': 1, '}': -1}.get(css[k], 0); k += 1
        inner = css[j + 1:k - 1]
        if sel.startswith('@media') or sel.startswith('@supports'):
            out.append(sel + '{' + scope(inner, p) + '}')
        elif sel.startswith('@'):
            out.append(sel + '{' + inner + '}')
        else:
            parts = [s.strip() for s in sel.split(',')]
            parts = [s for s in parts if s not in ('html', 'body')]
            if parts:
                out.append(','.join(p + ' ' + s for s in parts) + '{' + inner + '}')
        i = k
    return '\n'.join(out)

def port(name):
    src = open(os.path.join(DS, name, 'preview.html'), encoding='utf-8').read()
    style = re.search(r'<style>(.*?)</style>', src, re.S).group(1)
    body = re.search(r'<body>\n(.*?)\n<script>', src, re.S).group(1)
    m = re.search(r'<script>\n\(function \(\) \{\n(.*)\n\}\)\(\);\n</script>', src, re.S)
    script = m.group(1) if m else ''
    cfg = PROPS.get(name, {})
    for a, b in cfg.get('body', []):
        assert a in body, (name, a); body = body.replace(a, b)
    for a, b in cfg.get('script', []):
        assert a in script, (name, a); script = script.replace(a, b)
    # namespace every id so several components can share a page
    pfx = name.lower() + '-'
    ids = set(re.findall(r' id="([^"{]+)"', body))
    for x in sorted(ids, key=len, reverse=True):
        body = re.sub(r'(\b(?:id|for|aria-labelledby|aria-controls|aria-describedby)=")' + re.escape(x) + '"', r'\g<1>' + pfx + x + '"', body)
        script = re.sub(r"getElementById\((['\"])" + re.escape(x) + r"\1\)", "getElementById('" + pfx + x + "')", script)
        script = re.sub(r"(['\"])#" + re.escape(x) + r"(?![\w-])", r"\g<1>#" + pfx + x, script)
        script = re.sub(r"(['\"][^'\"]*?[ ,>])#" + re.escape(x) + r"(?![\w-])", r"\g<1>#" + pfx + x, script)
        style = re.sub(r"#" + re.escape(x) + r"(?![\w-])", "#" + pfx + x, style)
    if not cfg.get('body') and ('{' in body or '}' in body):
        body = body.replace('{', '&#123;').replace('}', '&#125;')
    locals_ = 'var gsap = window.gsap, ' + ', '.join(f'{x} = window.{x}' for x in PLUGINS) + ';'
    comp = f"""---
/* GENERATED by scripts/port-ds.py from design-system/components/{name}/preview.html. Edit the preview, then re-run. */
{cfg.get('front', '')}
---
<div class="ds-{name}">
{body}
</div>

<style is:global>{scope(style, '.ds-' + name)}</style>

<script>
  function start(window: any) {{
  {locals_}
{script}
  }}
  if ((window as any).gsap) start(window); else document.addEventListener('nb:gsap', () => start(window), {{ once: true }});
</script>
"""
    open(os.path.join(OUT, name + '.astro'), 'w', encoding='utf-8').write(comp)

os.makedirs(OUT, exist_ok=True)
for n in ['AsciiHero', 'ChapterOpener', 'AgentWindow', 'FloatingOps', 'StatusBoard', 'TheColleague', 'ThenNowCard', 'CinematicAscii']:
    port(n); print('ported', n)
