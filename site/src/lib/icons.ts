export type IconName = keyof typeof ICONS;

/* one SVG path of merged runs, crisp pixels, fill = currentColor (same technique as the logo) */
export const iconPath = (L: Bitmap) => {
  let d = '';
  L.rows.forEach((s, y) => { for (const m of s.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`; });
  return d;
};
export const iconSVG = (name: IconName, cls = 'nb-icon') => {
  const L = ICONS[name];
  return `<svg class="${cls}" viewBox="0 0 ${L.w} ${L.h}" shape-rendering="crispEdges" aria-hidden="true" focusable="false"><path fill="currentColor" d="${iconPath(L)}"/></svg>`;
};
